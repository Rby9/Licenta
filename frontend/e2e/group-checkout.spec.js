import { test, expect } from '@playwright/test';
import { mockCatalog } from './fixtures';
const quote = { hotelId: 1, hotelName: 'Hotel Demo', checkin: '2090-11-10', checkout: '2090-11-13', nights: 3, adults: 3, rooms: [{ categoryId: 1, name: 'Dublă', capacity: 2, adults: 2, nightlyCents: 19999, totalCents: 59997 }, { categoryId: 1, name: 'Dublă', capacity: 2, adults: 1, nightlyCents: 19999, totalCents: 59997 }], totalCents: 119994, dueNowCents: 119994, remainingCents: 0, quoteToken: 'synthetic-offer-token', onlineEnabled: true };
const url = `/rezervare/grup?${new URLSearchParams({ hotel_id: '1', checkin: quote.checkin, checkout: quote.checkout, rooms: JSON.stringify(quote.rooms.map(({ categoryId, adults }) => ({ categoryId, adults }))) })}`;
const group = { ...quote, id_grup: 7, status: 'confirmata', method: 'cash_cazare', paymentStatus: 'in_asteptare', dueNowCents: 0, reservations: [{ id_rezervare: 1 }, { id_rezervare: 2 }] };
for (const width of [390, 1440]) test(`checkout grup: aprobarea este obligatorie și cash confirmă toate camerele la ${width}px`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 900 });
  const failures = await mockCatalog(page);
  let approvals = 0, body;
  await page.route('**/api/rezervari-grup/oferta', route => { const method = route.request().postDataJSON().method; return route.fulfill({ json: { ...quote, dueNowCents: method === 'cash_cazare' ? 0 : quote.totalCents } }); });
  await page.route('**/api/rezervari-grup/aprobare', async route => { approvals++; body = route.request().postDataJSON(); await route.fulfill({ json: { group } }); });
  await page.route('**/api/rezervari-grup/7', route => route.fulfill({ json: group }));
  await page.goto(url);
  await expect(page.getByRole('region', { name: 'Oferta de rezervare' })).toContainText('1.199,94 RON');
  expect(approvals).toBe(0);
  await page.getByLabel('Metoda de plată').selectOption('cash_cazare');
  const button = page.getByRole('button', { name: 'Confirmă rezervarea cu plata la cazare' });
  await expect(button).toBeDisabled();
  await page.getByRole('checkbox').check();
  await expect(button).toBeEnabled();
  await page.screenshot({ path: testInfo.outputPath(`approval-${width}.png`) });
  await button.click();
  await expect(page.getByRole('heading', { name: 'Toate camerele sunt confirmate' })).toBeVisible();
  expect(approvals).toBe(1); expect(body).toEqual({ quoteToken: quote.quoteToken, approved: true });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Toate camerele sunt confirmate' })).toBeVisible();
  expect(approvals).toBe(1); expect(failures).toEqual([]);
});
test('checkout grup: schimbarea metodei invalidează acceptarea și avansul are rest explicit', async ({ page }) => {
  await mockCatalog(page);
  await page.route('**/api/rezervari-grup/oferta', route => { const method = route.request().postDataJSON().method; return route.fulfill({ json: { ...quote, dueNowCents: method === 'avans_online' ? 35998 : 119994 } }); });
  await page.goto(url);
  await page.getByRole('checkbox').check();
  await page.getByLabel('Metoda de plată').selectOption('avans_online');
  await expect(page.getByRole('button', { name: 'Aprobă și continuă la plata de 359,98 RON' })).toBeDisabled();
  await expect(page.getByRole('checkbox')).not.toBeChecked();
  await expect(page.getByRole('region')).toContainText('839,96 RON');
});
test('checkout grup: prețul schimbat cere verificare și o nouă aprobare', async ({ page }) => {
  await mockCatalog(page);
  await page.route('**/api/rezervari-grup/oferta', route => route.fulfill({ json: quote }));
  await page.route('**/api/rezervari-grup/aprobare', route => route.fulfill({ status: 409, json: { eroare: 'Prețul s-a schimbat. Cere o ofertă nouă.' } }));
  await page.goto(url); await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: /Aprobă și continuă/ }).click();
  await expect(page.getByRole('alert')).toContainText('Prețul s-a schimbat');
  await expect(page.getByRole('button', { name: /Aprobă și continuă/ })).toHaveCount(0);
  await page.getByRole('button', { name: 'Verifică din nou oferta / starea' }).click();
  await expect(page.getByRole('button', { name: /Aprobă și continuă/ })).toBeDisabled();
});
test('checkout grup: engleză și anulare explicită a întregului grup', async ({ page }) => {
  await mockCatalog(page);
  await page.route('**/api/rezervari-grup/7', route => route.fulfill({ json: group }));
  let cancellations = 0;
  await page.route('**/api/rezervari-grup/7/anulare', route => { cancellations++; expect(route.request().postDataJSON()).toEqual({ approved: true }); return route.fulfill({ json: { ...group, status: 'anulata' } }); });
  await page.goto('/rezervare/grup?group_id=7&lang=en');
  const button = page.getByRole('button', { name: 'Confirm cancellation of the whole group' });
  await expect(button).toBeDisabled(); expect(cancellations).toBe(0);
  await page.getByRole('checkbox').check(); await button.click();
  await expect(page.getByRole('heading', { name: 'Group booking cancelled' })).toBeVisible();
  expect(cancellations).toBe(1);
  await expect(page.getByText('Balance due at the property')).toHaveCount(0);
  await expect(page.getByText('Approved offer value')).toBeVisible();
});
test('checkout grup: autentificare înainte de ofertă și păstrarea destinației', async ({ page }) => {
  await mockCatalog(page, { authenticated: false });
  let requests = 0;
  await page.route('**/api/rezervari-grup/oferta', route => { requests++; return route.fulfill({ json: quote }); });
  await page.goto(url); await expect(page).toHaveURL(/\/autentificare$/);
  expect(requests).toBe(0);
  expect(await page.evaluate(() => sessionStorage.getItem('returnTo'))).toContain('/rezervare/grup?');
});
test('checkout grup: confirmarea online afișează starea grupului, fără altă aprobare', async ({ page }) => {
  await mockCatalog(page);
  let confirmations = 0;
  await page.route('**/api/rezervari-grup/confirmare', route => { confirmations++; return route.fulfill({ json: { ...group, method: 'online_total', paymentStatus: 'platita' } }); });
  await page.goto('/rezervare/grup?group_id=7&session_id=cs_test_demo');
  await expect(page.getByRole('heading', { name: 'Toate camerele sunt confirmate' })).toBeVisible();
  expect(confirmations).toBeGreaterThan(0);
  await expect(page.getByRole('button', { name: /Aprobă și continuă/ })).toHaveCount(0);
});
